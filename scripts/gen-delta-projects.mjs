import fs from "node:fs";
import path from "node:path";

const BASE = "src/components/sites/deltagroupnc-com-daf29435";
const PUB = "public/sites/deltagroupnc-com-daf29435";

const SOURCES = [
  { dir: "restaurant-construction-html-bd1f89cf", category: "Restaurant", route: "/restaurant-construction.html" },
  { dir: "nail-salon-construction-html-1c54b6a2", category: "Salon & Spa", route: "/nail-salon-construction.html" },
  { dir: "commercial-construction-html-1a4582f0", category: "Commercial", route: "/commercial-construction.html" },
  { dir: "residential-construction-html-491a1682", category: "Residential", route: "/residential-construction.html" },
];

const clean = (s) =>
  s
    .replace(/<br\s*\/?>/gi, " ")
    .replace(/\s+/g, " ")
    .trim();

const titleCase = (s) =>
  s
    .toLowerCase()
    .split(" ")
    .map((w) => (w.length > 2 || /^[0-9]/.test(w) ? w.charAt(0).toUpperCase() + w.slice(1) : w))
    .join(" ")
    .replace(/\bNc\b/g, "NC")
    .replace(/\bOf\b/g, "of")
    .replace(/\bAnd\b/g, "and")
    .replace(/\bThe\b/g, "The");

const slugify = (s) =>
  s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);

// prefer wide images for covers
const score = (f) => {
  const m = f.match(/(\d{3,4})x(\d{3,4})/);
  if (!m) return 0;
  const w = +m[1];
  return w >= 700 ? 3 : w >= 500 ? 2 : 1;
};

const out = [];
const seen = new Set();

for (const src of SOURCES) {
  const g = JSON.parse(fs.readFileSync(path.join(BASE, src.dir, "gallery.json"), "utf8"));
  for (const group of g.groups) {
    const raw = clean(group.title);
    const parts = raw.split(/\s*[–—]\s*/);
    const name = titleCase(parts[0]);
    let location = parts.slice(1).join(", ");
    location = titleCase(clean(location)).replace(/,\s*NC$/i, ", NC");
    const slug = slugify(name);
    if (seen.has(slug)) continue;
    seen.add(slug);
    const imgs = [...group.images].sort((a, b) => score(b) - score(a));
    const cover = imgs[0];
    const dirPub = path.join(PUB, src.dir, "images");
    if (!fs.existsSync(path.join(dirPub, cover))) continue;
    out.push({
      slug,
      name,
      location: location || "North Carolina",
      category: src.category,
      href: `${src.route}#${slugify(raw)}`,
      cover: `/sites/deltagroupnc-com-daf29435/${src.dir}/images/${cover}`,
      gallery: imgs.slice(0, 6).map((f) => `/sites/deltagroupnc-com-daf29435/${src.dir}/images/${f}`),
      photos: group.images.length,
    });
  }
}

const header = `// AUTO-GENERATED by scripts/gen-delta-projects.mjs — real project data extracted
// from the Delta Group gallery manifests. Do not edit by hand.

export interface DeltaProject {
  slug: string;
  name: string;
  location: string;
  category: "Restaurant" | "Salon & Spa" | "Commercial" | "Residential";
  href: string;
  cover: string;
  gallery: string[];
  photos: number;
}

export const PROJECTS: DeltaProject[] = ${JSON.stringify(out, null, 2)};

export const CATEGORIES = ["Restaurant", "Salon & Spa", "Commercial", "Residential"] as const;
`;

fs.writeFileSync("src/components/delta/data/projects.ts", header);
console.log("projects:", out.length, "photos:", out.reduce((a, b) => a + b.photos, 0));
